/*====================================================================================================
*
*   スムーススクロール
*
====================================================================================================*/

$(function () {
	// #で始まるリンクをクリックしたら実行される
	$('a[href^="#"]').click(function () {
		var speed = 400; // スクロール速度 - ミリ秒で記述
		var href = $(this).attr("href");
		var target = $(href == "#" || href == "" ? 'html' : href);
		var position = target.offset().top;
		$('body,html').animate({
			scrollTop: position
		}, speed, 'swing');
		return false;
	});
});


